export const EMOJI_KEYBOARD = [
  ...REACTION_EMOJIS,
  ...EMOJI_CATEGORIES.flatMap((c) => c.emojis),
];

export type ReactionView = {
  emoji: string;
  count: number;
  mine: boolean;
  users: { id: string; firstName: string }[];
};

export function normalizeReactionEmoji(raw: string): string | null {
  const emoji = [...raw.trim()].slice(0, 4).join("");
  if (!emoji) return null;
  if (/[<>"'\\]/.test(emoji)) return null;
  if (EMOJI_KEYBOARD.includes(emoji)) return emoji;
  return null;
}

export function packReactions(
  rows: { emoji: string; userId: string; user: { id: string; firstName: string } }[],
  meId: string,
): ReactionView[] {
  const map = new Map<string, ReactionView>();
  for (const row of rows) {
    const cur = map.get(row.emoji) || {
      emoji: row.emoji,
      count: 0,
      mine: false,
      users: [],
    };
    cur.count += 1;
    if (row.userId === meId) cur.mine = true;
    cur.users.push({ id: row.user.id, firstName: row.user.firstName });
    map.set(row.emoji, cur);
  }
  return [...map.values()];
}
